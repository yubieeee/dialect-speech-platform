def export_train_config(raw: dict[str, Any] | None = None) -> dict[str, Any]:
    ensure_lab_dirs()
    cfg = dict(DEFAULT_TRAIN)
    if raw:
        for key, value in raw.items():
            if key in cfg:
                cfg[key] = value
    if not cfg["pretrained_model_dir"]:
        from paths import DEFAULT_MODEL_DIR

        cfg["pretrained_model_dir"] = str(DEFAULT_MODEL_DIR)

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    out_dir = TRAIN_EXPORTS / f"{stamp}_{cfg['exp_name']}"
    out_dir.mkdir(parents=True, exist_ok=False)

    params_path = out_dir / "params.json"
    params_path.write_text(json.dumps(cfg, ensure_ascii=False, indent=2), encoding="utf-8")

    override_path = out_dir / "cosyvoice3.override.yaml"
    override_path.write_text(_render_override_yaml(cfg), encoding="utf-8")

    ds = {
        "train_micro_batch_size_per_gpu": int(cfg["ds_micro_batch_size"]),
        "gradient_accumulation_steps": int(cfg["ds_gradient_accumulation_steps"]),
        "steps_per_print": 100,
        "gradient_clipping": float(cfg["ds_gradient_clipping"]),
        "fp16": {"enabled": False},
        "bf16": {"enabled": False},
        "zero_force_ds_cpu_optimizer": False,
        "zero_optimization": {
            "stage": int(cfg["ds_zero_stage"]),
            "offload_optimizer": {"device": "none", "pin_memory": True},
            "allgather_partitions": True,
            "allgather_bucket_size": 5e8,
            "overlap_comm": False,
            "reduce_scatter": True,
            "reduce_bucket_size": 5e8,
            "contiguous_gradients": True,
        },
        "optimizer": {
            "type": "AdamW",
            "params": {
                "lr": float(cfg["ds_lr"]),
                "weight_decay": float(cfg["ds_weight_decay"]),
                "torch_adam": True,
                "adam_w_mode": True,
            },
        },
    }
    ds_path = out_dir / "ds_stage2.json"
    ds_path.write_text(json.dumps(ds, ensure_ascii=False, indent=2), encoding="utf-8")

    run_path = out_dir / "run_train.sh"
    run_path.write_text(_render_run_sh(cfg, out_dir), encoding="utf-8")
    run_path.chmod(0o755)

    readme = out_dir / "README.md"
    readme.write_text(
        "\n".join(
            [
                f"# {cfg['exp_name']} 训练导出",
                "",
                "- 本目录由 cosy-lab **仅导出配置**，不会启动训练。",
                "- 文昌当前语料极少时不要开训；先完成零样本 W2。",
                f"- 上游完整 yaml：`{UPSTREAM_YAML}`",
                f"- 上游 deepspeed：`{UPSTREAM_DS}`",
                "- 开训前请自行核对 data.list / parquet / 授权与磁盘。",
                "",
            ]
        ),
        encoding="utf-8",
    )

    if UPSTREAM_YAML.is_file():
        shutil.copy2(UPSTREAM_YAML, out_dir / "cosyvoice3.upstream.yaml")
    if UPSTREAM_DS.is_file():
        shutil.copy2(UPSTREAM_DS, out_dir / "ds_stage2.upstream.json")

    return {
        "ok": True,
        "out_dir": str(out_dir),
        "files": [p.name for p in sorted(out_dir.iterdir())],
        "params": cfg,
        "run_sh_preview": run_path.read_text(encoding="utf-8")[:2500],
    }


