def _render_run_sh(cfg: dict[str, Any], out_dir: Path) -> str:
    models = [cfg["model"]] if cfg["model"] != "all" else ["llm", "flow", "hifigan"]
    model_loop = " ".join(models)
    dpo_flag = "--dpo" if cfg.get("dpo") else ""
    ref_flag = f'--ref_model "{cfg["ref_model"]}"' if cfg.get("dpo") and cfg.get("ref_model") else ""
    pin = "--pin_memory" if cfg.get("pin_memory") else ""
    amp = "--use_amp" if cfg.get("use_amp") else ""
    return f"""#!/bin/bash
# Generated by cosy-lab — 仅作配置草稿，默认不要直接在生产机跑满 epoch
set -euo pipefail
export CUDA_VISIBLE_DEVICES="{cfg["cuda_visible_devices"]}"
pretrained_model_dir="{cfg["pretrained_model_dir"]}"
train_engine="{cfg["train_engine"]}"
num_gpus=$(echo "$CUDA_VISIBLE_DEVICES" | awk -F "," '{{print NF}}')
job_id=1986
dist_backend="{cfg["dist_backend"]}"
num_workers={int(cfg["num_workers"])}
prefetch={int(cfg["prefetch"])}

# 数据准备提示：参考 examples/libritts/cosyvoice3/run.sh stage 0~3
# prepare instruct 前缀: {cfg["data_instruct"]}

for model in {model_loop}; do
  torchrun --nnodes={int(cfg["nnodes"])} --nproc_per_node=$num_gpus \\
      --rdzv_id=$job_id --rdzv_backend="c10d" --rdzv_endpoint="{cfg["rdzv_endpoint"]}" \\
    ../../../cosyvoice/bin/train.py \\
    --train_engine $train_engine \\
    --config "{out_dir / "cosyvoice3.override.yaml"}" \\
    --train_data "{cfg["train_data_list"]}" \\
    --cv_data "{cfg["cv_data_list"]}" \\
    --qwen_pretrain_path "$pretrained_model_dir/CosyVoice-BlankEN" \\
    --onnx_path "$pretrained_model_dir" \\
    --model $model \\
    --checkpoint "$pretrained_model_dir/$model.pt" \\
    --model_dir "{out_dir / "exp"}/$model/$train_engine" \\
    --tensorboard_dir "{out_dir / "tensorboard"}/$model/$train_engine" \\
    --ddp.dist_backend $dist_backend \\
    --num_workers $num_workers \\
    --prefetch $prefetch \\
    {pin} {amp} {dpo_flag} {ref_flag} \\
    --deepspeed_config "{out_dir / "ds_stage2.json"}" \\
    --deepspeed.save_states {cfg["ds_save_states"]}
done
"""


